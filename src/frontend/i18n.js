let LANG = 'en';

function detectLang() {
  for (const l of navigator.languages || [navigator.language || 'en']) {
    const code = String(l).toLowerCase().split('-')[0];
    if (code === 'iw') return 'he';
    if (I18N[code]) return code;
  }
  return 'en';
}

function setLang(code) {
  LANG = I18N[code] ? code : detectLang();
  document.documentElement.lang = LANG;
  document.documentElement.dir = RTL_LANGS.has(LANG) ? 'rtl' : 'ltr';
  applyI18n();
}

// t('key', { n: 3 }) — falls back to English, then to the key itself.
function t(key, vars = {}) {
  let s = I18N[LANG]?.[key] ?? I18N.en[key] ?? key;
  if (typeof s === 'object') {
    const cat = new Intl.PluralRules(LANG).select(vars.n ?? 0);
    // Hebrew/Arabic etc. fall back to English's plural shape when a form is missing.
    s = s[cat] ?? s.other ?? (I18N.en[key]?.[cat] || I18N.en[key]?.other);
  }
  return String(s).replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
}

// A rejected tiny.api.call hands back a plain string, not an Error; accept both.
const errText = (e) => (typeof e === 'string' ? e : e?.message ?? String(e ?? ''));

// Backend errors arrive as "@code" or "@code|detail"; anything else is shown as is.
function tErr(e) {
  const msg = errText(e).replace(/^Error:\s*/, '');
  const m = /^@(\w+)(?:\|([\s\S]*))?$/.exec(msg);
  if (!m) return msg || t('err.unknown');
  return t('err.' + m[1], { d: m[2] ?? '' });
}

// Static text in index.html: data-i18n (text), data-i18n-ph (placeholder),
// data-i18n-title (tooltip).
function applyI18n() {
  for (const el of document.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll('[data-i18n-ph]')) el.placeholder = t(el.dataset.i18nPh);
  for (const el of document.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
}
